/* લખાણ ને વ્યક્તિઓ ની યાદી માં ફેરવે છે. newId() દરેક માટે નવું id આપે. */
BF.parseSeed = function (text, newId) {
  var out = [], stack = [], counters = {};
  text.split('\n').forEach(function (raw) {
    if (!raw.trim()) return;
    var depth = Math.floor(raw.match(/^ */)[0].length / 2);
    var s = raw.trim(), p = { alias: '', note: '', uncertain: false, pinned: false };
    var bar = s.indexOf('|');
    if (bar !== -1) { p.note = s.slice(bar + 1).trim(); s = s.slice(0, bar).trim(); }
    if (/!pin\b/.test(s)) { p.pinned = true; s = s.replace(/!pin\b/, '').trim(); }
    if (/!\?/.test(s)) { p.uncertain = true; s = s.replace(/!\?/, '').trim(); }
    p.gender = s.charAt(0) === '*' ? 'f' : 'm';
    if (p.gender === 'f') s = s.slice(1).trim();
    var am = s.match(/^(.*?)\s*\(([^)]*)\)\s*$/);
    if (am) { s = am[1]; p.alias = am[2].trim(); }
    p.name = s.trim();
    p.id = newId();
    stack.length = depth;
    var father = depth > 0 ? stack[depth - 1] : null;
    p.fatherId = father ? father.id : null;
    var key = p.fatherId || '_root';
    counters[key] = (counters[key] || 0) + 1;
    p.order = counters[key] * 10;
    stack[depth] = p;
    out.push(p);
  });
  return out;
};
